/** Index into a white-perspective table for a square at (row, col) in board() order. */
export function pstIndex(row, col) {
  return row * 8 + col
}

/** Mirror a white table index to black's perspective. */
export function mirrorIndex(idx) {
  const row = Math.floor(idx / 8)
  const col = idx % 8
  return (7 - row) * 8 + col
}
